def _pick(pool: list[str], seed_value: int) -> str:
    """Детерминированный выбор элемента по целочисленному сиду."""
    return pool[seed_value % len(pool)]


def _get_seed(sign: str, date_str: str, category: str) -> int:
    key = f"{sign}:{date_str}:{category}"
    return int(hashlib.md5(key.encode()).hexdigest(), 16)


def generate_daily_horoscope(sign: str, date_str: str) -> dict:
    """
    Создать детерминированный (но разнообразный) прогноз на день.

    sign:     русское название знака (напр. "Овен")
    date_str: "YYYY-MM-DD"
    Возвращает словарь с ключами general, love, finance, health.
    """
    element = SIGN_META.get(sign, {}).get("element", "огонь")
    prefix  = _ELEMENT_PREFIX.get(element, "")

    general = prefix + _pick(_GENERAL,  _get_seed(sign, date_str, "general"))
    love    =          _pick(_LOVE,     _get_seed(sign, date_str, "love"))
    finance =          _pick(_FINANCE,  _get_seed(sign, date_str, "finance"))
    health  =          _pick(_HEALTH,   _get_seed(sign, date_str, "health"))

    return {
        "general": general,
        "love":    love,
        "finance": finance,
        "health":  health,
    }
