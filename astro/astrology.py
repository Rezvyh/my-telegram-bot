def _lon_to_sign(lon_deg: float) -> str:
    """Перевести эклиптическую долготу (0–360°) в знак зодиака."""
    return ZODIAC_SIGNS[int(lon_deg / 30) % 12]


def get_sun_sign_by_date(birth_date: str) -> str:
    """
    Быстрое определение знака Солнца по дате (ДД.ММ.ГГГГ).
    Используется как запасной вариант без ephem.
    """
    day, month, _ = map(int, birth_date.split("."))
    md = month * 100 + day
    if   (321 <= md <= 419): return "Овен"
    elif (420 <= md <= 520): return "Телец"
    elif (521 <= md <= 620): return "Близнецы"
    elif (621 <= md <= 722): return "Рак"
    elif (723 <= md <= 822): return "Лев"
    elif (823 <= md <= 922): return "Дева"
    elif (923 <= md <= 1022): return "Весы"
    elif (1023 <= md <= 1121): return "Скорпион"
    elif (1122 <= md <= 1221): return "Стрелец"
    elif md >= 1222 or md <= 119: return "Козерог"
    elif (120 <= md <= 218): return "Водолей"
    else: return "Рыбы"


def get_city_coordinates(city_name: str) -> tuple[Optional[float], Optional[float]]:
    """Геокодирование города через OpenStreetMap Nominatim (бесплатно)."""
    geolocator = Nominatim(user_agent="astro_telegram_bot/1.0")
    try:
        location = geolocator.geocode(city_name, timeout=10)
        if location:
            logger.debug("Координаты '%s': %.4f, %.4f", city_name, location.latitude, location.longitude)
            return location.latitude, location.longitude
    except (GeocoderTimedOut, GeocoderServiceError) as e:
        logger.warning("Геокодирование не удалось для '%s': %s", city_name, e)
    return None, None


def calculate_natal_chart(
    birth_date: str,
    birth_time: str,
    lat: float,
    lon: float,
) -> dict:
    """
    Вычислить натальную карту: знак Солнца, Луны, Асцендент.

    birth_date: "ДД.ММ.ГГГГ"
    birth_time: "ЧЧ:ММ"
    lat, lon:   координаты места рождения
    """
    try:
        day, month, year = map(int, birth_date.split("."))
        hour, minute = map(int, birth_time.split(":"))

        obs = ephem.Observer()
        obs.lat  = str(lat)
        obs.lon  = str(lon)
        obs.elev = 0
        obs.pressure = 0
        obs.date = f"{year}/{month:02d}/{day:02d} {hour:02d}:{minute:02d}:00"

        # Знак Солнца
        sun = ephem.Sun(obs)
        sun_lon = math.degrees(float(sun.hlong))
        sun_sign = _lon_to_sign(sun_lon)

        # Знак Луны
        moon = ephem.Moon(obs)
        moon_lon = math.degrees(float(moon.hlong))
        moon_sign = _lon_to_sign(moon_lon)

        # Асцендент (знак восходящий на востоке в момент рождения)
        eps      = math.radians(23.437)          # наклон эклиптики
        lat_rad  = math.radians(lat)
        ramc     = float(obs.sidereal_time())    # местное звёздное время (рад)

        y = -math.cos(ramc)
        x = math.sin(eps) * math.tan(lat_rad) + math.cos(eps) * math.sin(ramc)
        asc_deg = math.degrees(math.atan2(y, x)) % 360
        asc_sign = _lon_to_sign(asc_deg)

        return {
            "sun_sign":  sun_sign,
            "moon_sign": moon_sign,
            "ascendant": asc_sign,
            "sun_lon":   round(sun_lon % 30, 1),
            "moon_lon":  round(moon_lon % 30, 1),
            "asc_lon":   round(asc_deg % 30, 1),
        }
    except Exception as e:
        logger.error("Ошибка расчёта натальной карты: %s", e)
        # Запасной вариант — только знак Солнца по дате
        sun_sign = get_sun_sign_by_date(birth_date)
        return {
            "sun_sign":  sun_sign,
            "moon_sign": "Неизвестно",
            "ascendant": "Неизвестно",
            "sun_lon":   0,
            "moon_lon":  0,
            "asc_lon":   0,
        }


